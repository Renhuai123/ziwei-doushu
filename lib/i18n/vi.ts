const periodStarNames = Object.fromEntries(
  Object.entries({ 运: 'đại hạn', 流: 'lưu niên', 月: 'lưu nguyệt', 日: 'lưu nhật', 时: 'lưu thời' })
    .flatMap(([prefix, period]) => Object.entries({ 魁: 'Thiên Khôi', 钺: 'Thiên Việt', 昌: 'Văn Xương', 曲: 'Văn Khúc', 鸾: 'Hồng Loan', 喜: 'Thiên Hỷ', 禄: 'Lộc Tồn', 羊: 'Kình Dương', 陀: 'Đà La', 马: 'Thiên Mã' })
      .map(([star, name]) => [`${prefix}${star}`, `${name} (${period})`]))
);

export const VI_TERMS: Readonly<Record<string, string>> = Object.freeze({
  ...Object.fromEntries(entries.trim().split('\n').map(line => {
    const split = line.indexOf('=');
    return [line.slice(0, split), line.slice(split + 1)];
  })),
  ...periodStarNames,
  ...VI_LOCATIONS,
  ...RESULT_TEXT_VI,
});

const escaped = Object.keys(VI_TERMS)
  .sort((a, b) => b.length - a.length)
  .map(key => key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
const tokens = new RegExp(escaped.join('|'), 'g');

/** Format domain labels without mutating the chart or changing lookup keys. */
export function viTerm(value: string | number | null | undefined): string {
  if (value == null) return '';
  const text = String(value);
  if (VI_TERMS[text]) return VI_TERMS[text];
  // Add spaces between adjacent translated Can/Chi or star abbreviations.
  return text.replace(/[\u3400-\u9fff]+/g, run =>
    VI_TERMS[run] ?? run.replace(tokens, token => `${VI_TERMS[token]} `).trim()
  );
}
